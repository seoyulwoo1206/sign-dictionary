// 두 손이 저마다 원을 그린다. 왼위상 = 왼손이 오른손보다 앞서 있는 각(180 = 엇갈리게, 0 = 나란히)
function 두손원({ 반지름 = 0.08, 면 = '정면', 바퀴 = 1, 방향 = 1, 시작각 = 90, 걸음 = 8, 시간 = 3, 왼위상 = 180, 오른기준 = {}, 왼기준 = {}, ...rest }) {
  const [a, b] = 면축[면];
  const at = (기준, a0, ang) => {
    const o = { ...기준 };
    o[a] = (o[a] || 0) + 반지름 * (Math.cos(ang) - Math.cos(a0));
    o[b] = (o[b] || 0) + 반지름 * (Math.sin(ang) - Math.sin(a0));
    return o;
  };
  const r0 = 시작각 * DEG, l0 = (시작각 + 왼위상) * DEG, n = 걸음 * 바퀴, out = [];
  for (let i = 1; i <= n; i++) {
    const d = (방향 * Math.PI * 2 * i) / 걸음;
    out.push({ 오른: { 옮김: at(오른기준, r0, r0 + d) }, 왼: { 옮김: at(왼기준, l0, l0 + d) }, 시간, 지나감: i < n, ...rest });
  }
  return out;
}
// 원을 그리면서 한쪽으로 옮겨 간다(나선). 이동 = 다 돌았을 때까지 옮겨 가는 양
function 나선(손, { 반지름 = 0.05, 면 = '정면', 바퀴 = 2, 방향 = 1, 시작각 = 90, 걸음 = 8, 시간 = 3, 기준 = {}, 이동 = {}, ...rest }) {
  const [a, b] = 면축[면];
  const a0 = 시작각 * DEG, n = 걸음 * 바퀴, out = [];
  for (let i = 1; i <= n; i++) {
    const ang = a0 + (방향 * Math.PI * 2 * i) / 걸음;
    const o = { ...기준 };
    for (const [k, w] of Object.entries(이동)) o[k] = (o[k] || 0) + (w * i) / n;
    o[a] = (o[a] || 0) + 반지름 * (Math.cos(ang) - Math.cos(a0));
    o[b] = (o[b] || 0) + 반지름 * (Math.sin(ang) - Math.sin(a0));
    out.push({ [손]: { 옮김: o }, 시간, 지나감: i < n, ...rest });
  }
  return out;
}

