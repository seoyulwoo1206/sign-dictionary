// 아래팔이 비스듬히 내려오게 한다. 어깨 높이에 두면 손목이 90° 가까이 꺾여 엔진이 손끝을 왼쪽으로 40°쯤 돌려 버린다
// (ㄴ처럼 보임). 이 자리에서는 적은 대로 손끝이 아래(정면에서 10° 안팎), 손등이 밖으로 보인다.
