const 자세 = (j) => {
  const [, dir, shape, base] = 표[j];
  return { 모양: shape || (base && 표[base][2]) || `지문자${base || j}`, ...방향묶음[dir] };
};

const JAMO = {};
for (const j of Object.keys(표)) {
  const [ref, , , base] = 표[j];
  const pose = 자세(j);
  const 동작 = [{ 오른: pose, 시간: 9, 멈춤: base ? 3 : 8 }];
  if (base) 동작.push({ 오른: { 옮김: { ...(pose.옮김 || {}), 오른: 0.13 + (pose.옮김?.오른 || 0) } }, 시간: 6, 멈춤: 5 });
  else 동작.push({ 오른: { 옮김: { ...(pose.옮김 || {}), 밖: 0.04 } }, 시간: 4, 멈춤: 3 });
  JAMO[j] = { ref, 동작 };
}
for (const [j, [ref, a, b]] of Object.entries(겹)) {
  JAMO[j] = { ref, 동작: [{ 오른: 자세(a), 시간: 9, 멈춤: 5 }, { 오른: 자세(b), 시간: 7, 멈춤: 7 }] };
}
